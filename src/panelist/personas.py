def get_persona(persona_type: PersonaType) -> dict[str, str]:
    """Get persona configuration.

    Args:
        persona_type: Type of persona

    Returns:
        Persona configuration dictionary

    Raises:
        ValueError: If persona type is invalid
    """
    if persona_type not in PERSONAS:
        raise ValueError(f"Invalid persona type: {persona_type}")

    return PERSONAS[persona_type]


def get_all_persona_types() -> list[PersonaType]:
    """Get all available persona types.

    Returns:
        List of persona types
    """
    return list(PERSONAS.keys())
